#!/usr/bin/env node
/**
 * Regenerates src/components/defaultFlow.js from worker.js.
 *
 * The app bundles a copy of the resolver flow so playback still works when the
 * worker is unreachable (or was never deployed). The copy must stay verbatim
 * identical to FLOW_SCRIPT — same text means the same content hash, so the app
 * compares versions correctly.
 *
 * Run after editing FLOW_SCRIPT:  npm run sync-flow
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const {pathToFileURL} = require('url');

const root = path.resolve(__dirname, '..');
const workerPath = path.join(root, 'worker.js');
const outPath = path.join(root, 'src', 'components', 'defaultFlow.js');

const START = 'const FLOW_SCRIPT = `';
const END = '\n`;';

const source = fs.readFileSync(workerPath, 'utf8');
const start = source.indexOf(START);
if (start < 0) {
  throw new Error(`could not find "${START}" in worker.js`);
}
const bodyStart = start + START.length;
const bodyEnd = source.indexOf(END, bodyStart);
if (bodyEnd < 0) {
  throw new Error('could not find the end of FLOW_SCRIPT in worker.js');
}
const body = source.slice(bodyStart, bodyEnd);

async function main() {
  // Import worker.js through a temporary .mjs so the version is computed by the
  // worker itself instead of by a copy of its hashing code.
  const tmp = path.join(os.tmpdir(), `tefrija-worker-${process.pid}.mjs`);
  fs.copyFileSync(workerPath, tmp);
  let version;
  try {
    const worker = await import(pathToFileURL(tmp).href);
    const response = await worker.default.fetch(
      new Request('https://worker.local/v1/flow'),
      {},
    );
    version = (await response.json()).version;
  } finally {
    fs.rmSync(tmp, {force: true});
  }

  const out = `// AUTO-GENERATED by scripts/sync-flow.js — do not edit by hand.
// Source of truth: worker.js (FLOW_SCRIPT). Re-run \`npm run sync-flow\` after
// editing the flow so the bundled copy matches the deployed one.
const FLOW_SCRIPT = \`${body}
\`;

export const DEFAULT_FLOW = {
  version: '${version}',
  script: FLOW_SCRIPT,
};
`;

  fs.writeFileSync(outPath, out);
  console.log(
    `wrote ${path.relative(root, outPath)} (version ${version}, ${
      body.length
    } chars)`,
  );
}

main().catch(error => {
  console.error(error);
  process.exit(1);
});
